import {
  formatUserTag,
  SEARCH_HIGHLIGHT_CLOSE,
  SEARCH_HIGHLIGHT_OPEN,
  type MessageSearchResponse,
} from "@pqp/shared";
import { getPool } from "../db.js";
import { isUuid } from "../lib/http.js";
import { channelVisibleSql } from "./users.js";

/**
 * Message search over Postgres full-text, with no second engine to operate.
 *
 * Nothing here names a text search configuration, and that is the point. The
 * query has to be stemmed exactly the way `messages.search_tsv` was, or it
 * matches nothing and the GIN index goes unused — a failure with no error to
 * notice. So the pair is defined once, in schema.sql, next to the generated
 * column: `pqp_search_query` builds the tsquery and `pqp_search_headline`
 * renders the snippet. Both sides move together or not at all.
 *
 * Today that pair is Portuguese and English, both accent-folded, ORed — see the
 * search block in schema.sql for why and what it costs.
 */

/**
 * Snippet shape. Two fragments so a match late in a long message still arrives
 * with context, and short ones because the result row is one line in a sidebar
 * panel rather than a document viewer.
 */
const HEADLINE_OPTIONS = [
  `StartSel="${SEARCH_HIGHLIGHT_OPEN}"`,
  `StopSel="${SEARCH_HIGHLIGHT_CLOSE}"`,
  "MaxFragments=2",
  "MaxWords=18",
  "MinWords=6",
  'FragmentDelimiter=" … "',
].join(", ");

/**
 * The visibility predicate, now generated by the shared `channelVisibleSql` in
 * services/users.ts rather than transcribed here. Search is the widest read
 * surface in the app — one query touching every message in a server — so it
 * must not carry a second, subtly different idea of who can see what, and the
 * only way to guarantee that is for the text to have one source.
 *
 * `$2` is the viewer, matching the `sm.user_id = $2` join below.
 */
const VISIBLE_CHANNEL = channelVisibleSql("$2");

interface SearchCursor {
  rank: number;
  createdAt: string;
  id: string;
}

/**
 * Results are ordered by relevance first, so a cursor has to carry the rank as
 * well as the row's position in time. `(created_at, id)` alone would skip
 * every later-but-less-relevant message.
 *
 * Postgres prints `real` with the shortest text that round-trips, so parsing it
 * to a JS number and casting it back to `real` in the next query reproduces the
 * same value exactly.
 *
 * `createdAt` IS A STRING FROM POSTGRES, NEVER A JS `Date`, and that is the
 * whole of what this file got wrong until 2026-09-09. `timestamptz` stores
 * microseconds; `Date` holds milliseconds; `toISOString()` therefore truncated
 * the boundary downward. Since the page predicate is a strict row comparison
 * against the same tuple the ordering uses, every equally-ranked row inside the
 * boundary's millisecond then compared GREATER than the cursor and was dropped
 * from the next page, and from every page after it. Skip-only, silent, and
 * `hasMore` still said the list was complete.
 *
 * The query hands the boundary back already formatted to microseconds in UTC
 * (`created_at_cursor` below), so no `Date` is involved in the round trip and
 * the value that goes out is the value that comes back.
 */
function encodeCursor(cursor: SearchCursor): string {
  return Buffer.from(
    `${cursor.rank}|${cursor.createdAt}|${cursor.id}`,
    "utf8",
  ).toString("base64url");
}

export function decodeSearchCursor(raw: string): SearchCursor | null {
  const decoded = Buffer.from(raw, "base64url").toString("utf8");
  const [rank, createdAt, id] = decoded.split("|");

  if (!rank || !createdAt || !id || !isUuid(id)) {
    return null;
  }
  const parsedRank = Number(rank);
  if (!Number.isFinite(parsedRank)) {
    return null;
  }
  // `Date.parse` is the shape check, not a conversion: V8 accepts the six
  // fractional digits Postgres emits (and the three an older cursor carries)
  // and the parsed number is thrown away. The string itself is what goes back
  // into `$8::timestamptz`, at whatever precision it arrived with.
  if (Number.isNaN(Date.parse(createdAt))) {
    return null;
  }
  return { rank: parsedRank, createdAt, id };
}

/**
 * What a search may be narrowed to besides its words (the header search's
 * chips). Every field is optional and each one only removes rows, so an empty
 * object is exactly the unfiltered search.
 */
export interface SearchFilters {
  /** One channel and the threads and forum posts under it. */
  channelId?: string;
  authorId?: string;
  /** Messages that mention this person. */
  mentionsId?: string;
  has?: SearchHas;
  /** On or after this UTC day, `YYYY-MM-DD`. */
  since?: string;
  /** Before this UTC day, `YYYY-MM-DD`. */
  until?: string;
}

export const SEARCH_HAS = ["link", "image", "file"] as const;
export type SearchHas = (typeof SEARCH_HAS)[number];

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
const DAY = /^\d{4}-\d{2}-\d{2}$/;

/**
 * The filters from a search URL. A malformed value is dropped rather than
 * refused: a stale chip should cost a filter, never the whole search.
 */
export function parseSearchFilters(params: URLSearchParams): SearchFilters {
  const id = (name: string) => {
    const value = params.get(name);
    return value && UUID.test(value) ? value : undefined;
  };
  const day = (name: string) => {
    const value = params.get(name);
    return value && DAY.test(value) && !Number.isNaN(Date.parse(value)) ? value : undefined;
  };
  const has = params.get("has");
  return {
    channelId: id("channelId"),
    authorId: id("authorId"),
    mentionsId: id("mentionsId"),
    has: (SEARCH_HAS as readonly string[]).includes(has ?? "") ? (has as SearchHas) : undefined,
    since: day("since"),
    until: day("until"),
  };
}

interface SearchRow {
  id: string;
  channel_id: string;
  channel_name: string;
  parent_channel_id: string | null;
  author_id: string;
  author_name: string;
  author_username: string | null;
  author_discriminator: string | null;
  author_avatar_url: string | null;
  created_at: Date;
  /**
   * The same instant as `created_at`, at the precision Postgres actually
   * stores, for the cursor. `created_at` stays a `Date` because the response
   * body is milliseconds and a client renders it; only the cursor needs to
   * survive a round trip exactly.
   */
  created_at_cursor: string;
  rank: number;
  snippet: string;
}

export async function searchMessages(
  serverId: string,
  viewerId: string,
  query: string,
  limit: number,
  cursor?: SearchCursor,
  filters: SearchFilters = {},
): Promise<MessageSearchResponse> {
  const params: unknown[] = [
    serverId,
    viewerId,
    query,
    limit + 1,
    HEADLINE_OPTIONS,
    // $6 — the StartSel `pqp_search_headline` looks for to decide whether the
    // Portuguese pass highlighted anything. Passed rather than restated in SQL
    // so the delimiters have one definition.
    SEARCH_HIGHLIGHT_OPEN,
  ];

  let cursorClause = "";
  if (cursor) {
    // Row comparison against the same expression the ordering uses: comparing
    // rank alone would drop every equally-ranked message after the first page.
    cursorClause = `AND (ts_rank_cd(m.search_tsv, q.query), m.created_at, m.id)
        < ($7::real, $8::timestamptz, $9::uuid)`;
    params.push(cursor.rank, cursor.createdAt, cursor.id);
  }

  // Each filter appends its own parameter, so the numbering follows whatever
  // the cursor took.
  const filterClauses: string[] = [];
  const bind = (value: unknown) => {
    params.push(value);
    return `$${params.length}`;
  };
  if (filters.channelId) {
    const id = bind(filters.channelId);
    filterClauses.push(`AND (m.channel_id = ${id}::uuid OR (c.type = 'thread' AND c.parent_id = ${id}::uuid))`);
  }
  if (filters.authorId) {
    filterClauses.push(`AND m.author_id = ${bind(filters.authorId)}::uuid`);
  }
  if (filters.mentionsId) {
    filterClauses.push(
      `AND EXISTS (SELECT 1 FROM message_mentions mm WHERE mm.message_id = m.id AND mm.user_id = ${bind(filters.mentionsId)}::uuid)`,
    );
  }
  if (filters.has === "link") {
    filterClauses.push(`AND m.body ~* 'https?://'`);
  } else if (filters.has === "image") {
    filterClauses.push(
      `AND EXISTS (SELECT 1 FROM message_attachments a WHERE a.message_id = m.id AND a.content_type LIKE 'image/%')`,
    );
  } else if (filters.has === "file") {
    filterClauses.push(
      `AND EXISTS (SELECT 1 FROM message_attachments a WHERE a.message_id = m.id AND a.content_type NOT LIKE 'image/%')`,
    );
  }
  if (filters.since) {
    filterClauses.push(`AND m.created_at >= (${bind(filters.since)}::date)::timestamp AT TIME ZONE 'UTC'`);
  }
  if (filters.until) {
    filterClauses.push(`AND m.created_at < (${bind(filters.until)}::date)::timestamp AT TIME ZONE 'UTC'`);
  }

  // `hits` is limited before the outer select runs, so ts_headline — which
  // re-parses the whole body — is only paid for the rows actually returned.
  const result = await getPool().query<SearchRow>(
    `WITH q AS (SELECT pqp_search_query($3) AS query),
     hits AS (
       SELECT m.id, m.channel_id, m.author_id, m.body, m.created_at,
              c.name AS channel_name,
              -- A thread or a forum post: the channel it sits under, so a
              -- hit can open the forum (or the text channel) with the post on
              -- top. Null for every other channel, whose parent_id is at most
              -- a category, which is not where a hit opens.
              CASE WHEN c.type = 'thread' THEN c.parent_id END
                AS parent_channel_id,
              u.display_name AS author_name,
              u.username AS author_username,
              u.discriminator AS author_discriminator,
              u.avatar_url AS author_avatar_url,
              ts_rank_cd(m.search_tsv, q.query) AS rank
       FROM messages m
       CROSS JOIN q
       JOIN channels c ON c.id = m.channel_id
       JOIN users u ON u.id = m.author_id
       JOIN server_members sm ON sm.server_id = c.server_id AND sm.user_id = $2
       WHERE c.server_id = $1
         AND m.search_tsv @@ q.query
         AND ${VISIBLE_CHANNEL}
         ${cursorClause}
         ${filterClauses.join("\n         ")}
       ORDER BY rank DESC, m.created_at DESC, m.id DESC
       LIMIT $4
     )
     SELECT h.id, h.channel_id, h.channel_name, h.parent_channel_id,
            h.author_id, h.author_name,
            h.author_username, h.author_discriminator, h.author_avatar_url,
            h.created_at, h.rank,
            -- Microseconds, explicit UTC, unambiguous to a timestamptz cast
            -- on the way back in. to_char rather than a plain ::text cast,
            -- because that one renders in the session's TimeZone.
            to_char(h.created_at AT TIME ZONE 'UTC',
                    'YYYY-MM-DD"T"HH24:MI:SS.US"Z"') AS created_at_cursor,
            pqp_search_headline(h.body, q.query, $5, $6) AS snippet
     FROM hits h
     CROSS JOIN q
     ORDER BY h.rank DESC, h.created_at DESC, h.id DESC`,
    params,
  );

  const hasMore = result.rows.length > limit;
  const rows = result.rows.slice(0, limit);
  const last = rows[rows.length - 1];

  return {
    hasMore,
    nextCursor:
      hasMore && last
        ? encodeCursor({
            rank: last.rank,
            // NOT `last.created_at.toISOString()`: that is a `Date`, and a
            // `Date` cannot hold the microseconds the row is ordered by.
            createdAt: last.created_at_cursor,
            id: last.id,
          })
        : null,
    results: rows.map((row) => ({
      messageId: row.id,
      channelId: row.channel_id,
      channelName: row.channel_name,
      parentChannelId: row.parent_channel_id,
      authorId: row.author_id,
      authorName: row.author_name,
      authorTag: formatUserTag(row.author_username, row.author_discriminator),
      authorAvatarUrl: row.author_avatar_url,
      snippet: row.snippet,
      createdAt: row.created_at.toISOString(),
    })),
  };
}

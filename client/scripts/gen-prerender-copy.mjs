#!/usr/bin/env node
/**
 * Writes `src/lib/marketing-prerender-copy.ts`: the catalogue strings the
 * no-JS bodies of `/tela`, `/vs-discord` and `/download` read.
 *
 * The Pages middleware cannot import the catalogues, so the strings are
 * duplicated. Rerun this after changing any key below in a catalogue:
 *
 *   pnpm --filter @pqp/client prerender:copy
 *
 * `marketing-prerender.test.ts` fails when the file and the catalogues differ.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const LOCALES = ["pt-BR", "en", "es"];

const PAGES = {
  TELA: [
    "tela.hero.title",
    "tela.hero.lede",
    "tela.hero.note",
    "tela.hero.disclosure",
    "tela.options.title",
    "tela.options.goodFor",
    "tela.options.limit",
    "tela.options.ours",
    "tela.options.asOf",
    ...["pqp", "jitsi", "teamspeak", "meet"].flatMap((id) =>
      ["name", "body", "good", "limit"].map((part) => `tela.option.${id}.${part}`),
    ),
    "tela.how.title",
    "tela.how.1",
    "tela.how.2",
    "tela.how.3",
    "tela.faq.title",
    ...["download", "vpn", "people", "free", "mobile", "data", "why"].flatMap((id) => [
      `tela.faq.${id}.q`,
      `tela.faq.${id}.a`,
    ]),
    "tela.faq.data.link",
    "tela.cta.title",
    "tela.cta.body",
    "tela.cta.create",
    "tela.cta.compare",
  ],
  VS_DISCORD: [
    "vsDiscord.hero.tagline",
    "vsDiscord.hero.body",
    "vsDiscord.hero.disclaimer",
    "vsDiscord.row.screen.label",
    "vsDiscord.chip.works",
    "vsDiscord.chip.suspended",
    "vsDiscord.chip.yes",
    "vsDiscord.chip.no",
    "vsDiscord.chip.partial",
    "vsDiscord.featured.pqpDetail",
    "vsDiscord.featured.discordDetail",
    "vsDiscord.table.title",
    "vsDiscord.table.caption",
    "vsDiscord.table.col.feature",
    "vsDiscord.table.col.pqp",
    "vsDiscord.table.col.discord",
    ...[
      "price",
      "openSource",
      "selfHost",
      "ageGate",
      "apps",
      "ecosystem",
      "maturity",
      "region",
    ].flatMap((id) => ["label", "pqp", "discord"].map((part) => `vsDiscord.row.${id}.${part}`)),
    "vsDiscord.faq.title",
    ...["why", "when", "how", "catch"].flatMap((id) => [
      `vsDiscord.faq.${id}.q`,
      `vsDiscord.faq.${id}.a`,
    ]),
    "vsDiscord.closing.title",
    "vsDiscord.closing.body",
    "vsDiscord.closing.tela.lead",
    "vsDiscord.closing.tela.link",
    "vsDiscord.cta.create",
    "vsDiscord.cta.beta",
  ],
  DOWNLOAD: [
    "downloadPage.title",
    "downloadPage.body",
    "downloadPage.web.cta",
    "downloadPage.all",
    "downloadPage.windows",
    "downloadPage.mac",
    "downloadPage.linux",
    "downloadPage.ios",
    "downloadPage.android",
    "downloadPage.list.download",
    "downloadPage.list.ios",
    "downloadPage.list.android",
    "download.windows.portableShort",
    "download.mac.appleSiliconShort",
    "download.mac.intelShort",
    "download.linux.appImage",
    "download.linux.deb",
    "download.linux.flatpak",
    "download.other",
    "codeSigning.title",
    "codeSigning.status",
    "codeSigning.creditNote",
    "codeSigning.unsigned",
    "codeSigning.link.signpath",
    "codeSigning.link.terms",
    "codeSigning.team.title",
    "codeSigning.team.committers",
    "codeSigning.team.committers.desc",
    "codeSigning.team.approvers",
    "codeSigning.team.approvers.desc",
    "codeSigning.how.title",
    "codeSigning.how.build",
    "codeSigning.how.approve",
    "codeSigning.how.scope",
    "codeSigning.link.repo",
    "codeSigning.link.workflow",
    "codeSigning.privacy.title",
    "codeSigning.privacy.installer",
    "codeSigning.privacy.app",
    "codeSigning.privacy.signpath",
    "codeSigning.privacy.link",
  ],
};

const catalogues = Object.fromEntries(
  LOCALES.map((locale) => [
    locale,
    JSON.parse(readFileSync(path.join(root, `src/locales/${locale}/translation.json`), "utf8")),
  ]),
);

const out = [
  "// Generated by `scripts/gen-prerender-copy.mjs` from the catalogues. Do not edit by hand:",
  "// change the catalogue, then run `pnpm --filter @pqp/client prerender:copy`.",
  "",
];
for (const [name, keys] of Object.entries(PAGES)) {
  out.push(`export const ${name}_PRERENDER_KEYS = ${JSON.stringify(keys, null, 2)} as const;`, "");
  const copy = {};
  for (const locale of LOCALES) {
    copy[locale] = {};
    for (const key of keys) {
      const value = catalogues[locale][key];
      if (typeof value !== "string" || !value) {
        throw new Error(`${locale} is missing ${key}`);
      }
      copy[locale][key] = value;
    }
  }
  out.push(
    `export const ${name}_PRERENDER_COPY: Record<"pt-BR" | "en" | "es", Record<(typeof ${name}_PRERENDER_KEYS)[number], string>> = ${JSON.stringify(copy, null, 2)};`,
    "",
  );
}
writeFileSync(path.join(root, "src/lib/marketing-prerender-copy.ts"), out.join("\n"));
